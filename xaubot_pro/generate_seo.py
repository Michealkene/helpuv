# Generate sitemap
def generate_sitemap():
    urls = [f"  <url><loc>{DOMAIN}/</loc><priority>1.0</priority></url>"]
    for p in PAGES:
        urls.append(f"  <url><loc>{DOMAIN}/{p['slug']}</loc><priority>0.8</priority></url>")
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
{chr(10).join(urls)}
</urlset>"""

